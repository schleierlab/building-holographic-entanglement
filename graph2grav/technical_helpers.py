def get_boundary_nodes_by_position(
    graph: nx.Graph,
    kept_indices: Optional[List[int]] = None
) -> Tuple[Dict[int, List[int]], List[int]]:
    """
    Identifies boundary nodes and groups their phase space indices by position.
    If kept_indices is provided, maps original indices to their position within kept_indices.

    Assumes nodes have 'is_boundary' (bool) and 'position_in_boundary' (int) attributes.
    Node indices are assumed to be the phase space indices (0 to 2N-1).

    Args:
        graph: The networkx graph.
        kept_indices: Optional list of the original phase space indices that remain after measurement.
                      If provided, the returned indices will be relative to this list.

    Returns:
        A tuple containing:
        - A dictionary mapping boundary position -> sorted list of phase space node indices
          (relative to kept_indices if provided, otherwise original).
        - A sorted list of unique boundary positions found among the kept nodes.
    """
    boundary_nodes_map = defaultdict(list)
    positions = set()

    # Create a lookup for fast checking if an index is kept and its new position
    kept_indices_lookup = {original_idx: new_idx for new_idx, original_idx in enumerate(kept_indices)} if kept_indices is not None else None

    for node, data in graph.nodes(data=True):
        if data.get('is_boundary', False):
            position = data.get('position_in_boundary')
            if position is not None:
                # Node index 'node' is the original phase space index
                original_phase_space_index = node

                if kept_indices_lookup is not None:
                    # Check if this boundary node's index is in the kept indices
                    if original_phase_space_index in kept_indices_lookup:
                        new_index = kept_indices_lookup[original_phase_space_index]
                        boundary_nodes_map[position].append(new_index)
                        positions.add(position) # Only add position if a kept node exists there
                    # else: This boundary node was measured out, ignore it.
                else:
                    # No measurement, use original index
                    boundary_nodes_map[position].append(original_phase_space_index)
                    positions.add(position)
            else:
                # Optional: Add a warning if a boundary node is missing the position attribute
                # Avoid warning if the node wasn't kept anyway
                if kept_indices_lookup is None or original_phase_space_index in kept_indices_lookup:
                    print(f"Warning: Boundary node {node} is missing 'position_in_boundary' attribute.")

    # Sort the node indices within each position list
    for pos in boundary_nodes_map:
        boundary_nodes_map[pos].sort()

    # Filter out positions that might have been added initially but ended up with no kept nodes
    # (Shouldn't happen with current logic, but good practice)
    final_boundary_nodes_map = {pos: indices for pos, indices in boundary_nodes_map.items() if indices}
    unique_sorted_positions = sorted(list(final_boundary_nodes_map.keys()))

    return dict(final_boundary_nodes_map), unique_sorted_positions



