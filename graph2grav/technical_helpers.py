def generate_non_overlapping_regions_v2(
    L: int,
    mingap: int = 0,
    assume_rotational_invariance: bool = False
) -> List[Tuple[List[int], List[int], List[int]]]:
    """
    Generates all unique combinations of three non-overlapping regions
    of sequential integers modulo L, with a minimum gap between regions.

    Generated by Gemini 2.5 Pro, modified by Copilot.

    Args:
        L: The total length (modulus). Must be >= 3.
        mingap: The minimum required gap between the end of one region
                and the start of the next (cyclically). Must be >= 0.
        assume_rotational_invariance: If True, assumes rotational invariance
                                      and only generates one representative
                                      configuration for each composition,
                                      skipping the L rotations. Defaults to False.

    Returns:
        A list of tuples. Each tuple contains three lists, where each list
        represents a region [start, start+1, ..., end] (mod L).
        The list contains all unique combinations, avoiding permutations
        of the same set of three regions.
    """
    # Need at least L=3 for 3 regions of length 1 (with 0 gaps)
    if not isinstance(L, int) or L < 3:
        print("L must be an integer >= 3")
        return []
    if not isinstance(mingap, int) or mingap < 0:
        raise ValueError("mingap must be a non-negative integer")

    # Use a set to automatically handle duplicates after canonicalization
    # The canonical form: tuple(sorted(tuple(region) for region in triple by start element))
    results_set: Set[Tuple[Tuple[int, ...], Tuple[int, ...], Tuple[int, ...]]] = set()

    # Map to compositions of N' into 6 positive integers (l'_1..3, g'_1..3)
    # where l_i = l'_i >= 1
    # and g_i = g'_i - 1 + mingap >= mingap
    # Sum: l1+l2+l3+g1+g2+g3 = L
    # Sum': l'_1+l'_2+l'_3+g'_1+g'_2+g'_3 = L - 3*mingap + 3
    target_sum = L - 3 * mingap + 3
    num_parts = 6

    # Check if composition is possible (need 6 parts >= 1)
    if target_sum < num_parts:
        # This happens if L < 3*mingap + 3
        # print(f"Warning: No combinations possible for L={L} and mingap={mingap}")
        return []

    # Iterate through compositions using stars and bars
    # Choose k-1=5 divider positions from n-1 = target_sum-1 possible spots
    for dividers in itertools.combinations(range(1, target_sum), num_parts - 1):
        # Calculate the value of each part (l'_1, l'_2, l'_3, g'_1, g'_2, g'_3)
        all_dividers = (0,) + dividers + (target_sum,)
        parts = [all_dividers[i+1] - all_dividers[i] for i in range(num_parts)]

        # Extract region lengths (l_i >= 1) and gap lengths (g_i >= mingap)
        l1, l2, l3 = parts[0], parts[1], parts[2]
        g1 = parts[3] - 1 + mingap
        g2 = parts[4] - 1 + mingap
        g3 = parts[5] - 1 + mingap

        # --- Construct the base configuration (starting R1 at 0) ---
        regions_base = []
        current_pos = 0

        # Region 1
        r1_list = [(current_pos + i) % L for i in range(l1)]
        if not r1_list: continue # Should not happen if l1 >= 1
        regions_base.append(r1_list)
        current_pos = (current_pos + l1 + g1) % L # Position for start of R2

        # Region 2
        r2_list = [(current_pos + i) % L for i in range(l2)]
        if not r2_list: continue # Should not happen if l2 >= 1
        regions_base.append(r2_list)
        current_pos = (current_pos + l2 + g2) % L # Position for start of R3

        # Region 3
        r3_list = [(current_pos + i) % L for i in range(l3)]
        if not r3_list: continue # Should not happen if l3 >= 1
        regions_base.append(r3_list)

        if assume_rotational_invariance:
            # --- Only canonicalize and add the base configuration ---
            try:
                # Sort the list of lists (regions) based on their numeric starting element
                sorted_regions = sorted(regions_base, key=lambda r: r[0])
                # Convert inner lists to tuples for hashability
                canonical_form = tuple(tuple(r) for r in sorted_regions)
                results_set.add(canonical_form)
            except IndexError:
                 # This guards against unforeseen empty regions, though l_i>=1 should prevent it.
                 pass
        else:
            # --- Generate all L rotations of this base configuration ---
            for shift in range(L):
                rotated_triple_list = []
                for region_list in regions_base:
                     # Apply shift and ensure elements are mod L
                     shifted_list = [(x + shift) % L for x in region_list]
                     rotated_triple_list.append(shifted_list)

                # --- Canonicalize and add to set ---
                try:
                    # Sort the list of lists (regions) based on their numeric starting element
                    sorted_regions = sorted(rotated_triple_list, key=lambda r: r[0])
                    # Convert inner lists to tuples for hashability
                    canonical_form = tuple(tuple(r) for r in sorted_regions)
                    results_set.add(canonical_form)
                except IndexError:
                     # This guards against unforeseen empty regions, though l_i>=1 should prevent it.
                     pass

    # Convert the canonical tuples back to the desired list of tuples of lists
    final_list: List[Tuple[List[int], List[int], List[int]]] = []
    for canonical_tuple in results_set:
        triple_of_lists = tuple(list(r) for r in canonical_tuple)
        final_list.append(triple_of_lists) # type: ignore

    return final_list

