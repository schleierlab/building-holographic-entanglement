def cycle_python_matrix(matrix):
    """Cycles the rows and columns of a square matrix.

    Args:
        matrix: A square matrix represented as a list of lists.

    Returns:
        The cycled matrix.
    """

    # Cycle rows
    matrix = matrix[1:] + [matrix[0]]

    # Cycle columns
    for i in range(len(matrix)):
        matrix[i] = matrix[i][1:] + [matrix[i][0]]

    return matrix

def cycle_matrix(matrix):
    """Cycles the rows and columns of a square numpy matrix."""

    # Cycle rows
    matrix = np.roll(matrix, 1, axis=0)

    # Cycle columns
    matrix = np.roll(matrix, 1, axis=1)

    return matrix

