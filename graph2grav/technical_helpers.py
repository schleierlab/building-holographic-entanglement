def calculate_jacobi_transformation_matrix(masses):
    """
    Calculates the 2N x 2N symplectic transformation matrix M for
    transforming from individual particle coordinates (x_i, p_i) to
    center-of-mass and Jacobi relative coordinates (R_CM, P_CM, rho_k, pi_k).

    Args:
        masses (list or np.ndarray): A list or NumPy array of N particle masses.

    Returns:
        np.ndarray: The 2N x 2N transformation matrix M.
    """
    masses = np.array(masses, dtype=float)
    n = len(masses)
    if n == 0:
        return np.array([[]])
    if np.any(masses <= 0):
        print("Warning: Masses should generally be positive.")

    m_tot = np.sum(masses)
    if m_tot == 0:
         raise ValueError("Total mass cannot be zero.")

    # Initialize N x N blocks A and D
    A = np.zeros((n, n))
    D = np.zeros((n, n))

    # --- Fill A Matrix (X' = AX) ---
    # Row 0: R_CM = sum(m_j * x_j) / M_tot
    A[0, :] = masses / m_tot

    # Rows 1 to N-1: rho_k = x_{k+1} - sum(m_j * x_j) / sum(m_j) [for j=1..k]
    # Corresponds to A[k, :] where k is row index (0-based)
    current_m_sum = 0.0
    for k in range(n - 1): # k runs from 0 to n-2
        current_m_sum += masses[k]
        if current_m_sum == 0:
            raise ValueError(f"Sum of first {k+1} masses is zero, division by zero.")

        # Coefficient of x_{k+1} (column k+1) is 1
        A[k + 1, k + 1] = 1.0
        # Coefficients of x_j for j=0..k (columns 0..k)
        for j in range(k + 1):
            A[k + 1, j] -= masses[j] / current_m_sum

    # --- Fill D Matrix (P' = DP) ---
    # Row 0: P_CM = sum(p_j)
    D[0, :] = 1.0

    # Rows 1 to N-1: pi_k = (sum_1^k(m_j) * p_{k+1} - m_{k+1} * sum_1^k(p_j)) / sum_1^{k+1}(m_j)
    # Corresponds to D[k, :] where k is row index (0-based)
    current_m_sum = 0.0
    for k in range(n - 1): # k runs from 0 to n-2
        m_k_plus_1 = masses[k+1]
        m_sum_partial = current_m_sum + masses[k] # sum m_1 to m_{k+1}
        m_sum_total = m_sum_partial + m_k_plus_1 # sum m_1 to m_{k+2} -> Mistake here, check indices
        # Let's retry index logic matching the formula using k_jacobi = 1..N-1
        # We fill row i_prime = 1..N-1
        # i_prime = k_jacobi corresponds to rho_{k_jacobi}, pi_{k_jacobi}

        # Reset and recalculate sums based on i_prime = 1 to n-1 (row index)
        # This corresponds to jacobi index k = i_prime - 1
        # We need sum up to k (i_prime -1) and sum up to k+1 (i_prime)

    m_sum_partial = 0.0 # Sum m_1 .. m_k
    for i_prime in range(1, n): # i_prime runs 1 to n-1 (row index)
         # Corresponds to Jacobi index k = i_prime - 1
         k = i_prime - 1
         m_k_plus_1 = masses[k + 1] # mass m_{k+1}
         m_sum_1_to_k = np.sum(masses[:k+1]) # Sum m_1 to m_{k+1}
         m_sum_1_to_k_plus_1 = np.sum(masses[:k+2]) # Sum m_1 to m_{k+2}

         if m_sum_1_to_k_plus_1 == 0:
             raise ValueError(f"Sum of first {k+2} masses is zero, division by zero.")

         # Coefficient of p_{k+1} (column k+1)
         D[i_prime, k + 1] = m_sum_1_to_k / m_sum_1_to_k_plus_1

         # Coefficients of p_j for j=0..k (columns 0..k)
         coeff_pj = -m_k_plus_1 / m_sum_1_to_k_plus_1
         for j in range(k + 1):
             D[i_prime, j] = coeff_pj

    # --- Assemble the full 2N x 2N Matrix M ---
    M_matrix = np.zeros((2 * n, 2 * n))

    for i_prime in range(n):
        for j_prime in range(n):
            # Indices in the 2N x 2N matrix
            i_x = 2 * i_prime
            i_p = 2 * i_prime + 1
            j_x = 2 * j_prime
            j_p = 2 * j_prime + 1

            # Place elements from A and D
            M_matrix[i_x, j_x] = A[i_prime, j_prime]
            M_matrix[i_p, j_p] = D[i_prime, j_prime]
            # B and C blocks are implicitly zero from initialization

    return M_matrix

def canon_cycle_4(c):
    """Returns the canonical form of a 4-cycle for de-duplication.

    Given a 4-cycle [u, a, v, b], computes all 8 equivalent representations
    (4 rotations and 4 rotations of the reverse) and returns the
    lexicographically minimal tuple. This ensures that cycles differing only
    by rotation or direction map to the same canonical representative.

    Args:
        c: A sequence of 4 elements representing a cycle [u, a, v, b].

    Returns:
        The lexicographically minimal tuple among all rotations and reversals.

    Example:
        >>> canon_cycle_4([2, 1, 3, 0])
        (0, 2, 1, 3)  # Represents rotation/reversal of the input
    """
    c = list(c)
    rots = [tuple(c[i:]+c[:i]) for i in range(4)]
    r = list(reversed(c))
    rotsR = [tuple(r[i:]+r[:i]) for i in range(4)]
    return min(rots + rotsR)

def chordless_4cycles_nodes(G: nx.Graph):
    """
    All chordless 4-cycles {u,a,v,b} with edges u-a, a-v, v-b, b-u, and NO chords u-v, a-b.
    Uses opposite-corner pairs (u,v) that are NOT adjacent and have two distinct common neighbors.
    De-duplicates via canonical cyclic form.
    """
    C = set()
    neigh = {n: set(G[n]) for n in G.nodes()}
    nodes = list(G.nodes())
    # unordered non-edges as opposite corners
    for i, u in enumerate(nodes):
        Nu = neigh[u]
        for v in nodes[i+1:]:
            if v in Nu:  # skip edges; opposite corners must be non-adjacent (chordless)
                continue
            S = Nu & neigh[v]          # common neighbors = the other two corners
            for a, b in it.combinations(sorted(S), 2):
                if a == b or a in (u, v) or b in (u, v):
                    continue
                # enforce CHORDLESS: the other opposite pair (a,b) must also be non-adjacent
                if b in neigh[a]:
                    continue
                cyc = canon_cycle_4([u, a, v, b])
                C.add(cyc)
    return list(C)

def triangles_nodes(G):
    """All 3-cycles via cliques; fast and complete for triangles."""
    tris = []
    for c in nx.enumerate_all_cliques(G):
        if len(c) == 3:
            u, v, w = c
            # canonicalize triangle (smallest rotation ignoring direction)
            rots = [tuple(c[i:]+c[:i]) for i in range(3)]
            r = list(reversed(c))
            rotsR = [tuple(r[i:]+r[:i]) for i in range(3)]
            tris.append(min(rots + rotsR))
